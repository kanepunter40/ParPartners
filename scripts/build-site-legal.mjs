// Builds the website's legal pages from the same texts the app shows, so the two never drift apart:
//   site/privacy/, site/terms/, site/imprint/  <- src/app/pages/legal/legal-texts(.de).ts
//   site/delete-account/                       <- written below (Google Play needs a web page for this)
// Run after changing the legal texts:  npm run site:legal   (then commit site/)
import { build } from 'esbuild';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const site = join(root, 'site');

// Load the TypeScript texts by bundling them into one ES module in memory
const out = await build({
  stdin: {
    contents: `export * from './legal-texts'; export * from './legal-texts.de';`,
    resolveDir: join(root, 'src/app/pages/legal'),
    loader: 'ts'
  },
  bundle: true, format: 'esm', write: false, platform: 'neutral', logLevel: 'silent'
});
const texts = await import('data:text/javascript;base64,' + Buffer.from(out.outputFiles[0].text).toString('base64'));
const en = JSON.parse(readFileSync(join(root, 'src/app/i18n/en.json'), 'utf8'));
const de = JSON.parse(readFileSync(join(root, 'src/app/i18n/de.json'), 'utf8'));

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
/** Turns the contact email into a link; everything else stays plain text. */
const linkify = (s) => esc(s).replaceAll(esc(texts.CONTACT), `<a href="mailto:${texts.CONTACT}">${esc(texts.CONTACT)}</a>`);

const NAV = [
  ['privacy', 'Privacy', 'Datenschutz'],
  ['terms', 'Terms', 'Nutzungsbedingungen'],
  ['delete-account', 'Delete account', 'Konto löschen'],
  ['imprint', 'Imprint', 'Impressum']
];

function docHtml(doc, updatedLabel) {
  return `
    <h1>${esc(doc.title)}</h1>
    ${doc.intro ? `<p class="intro">${linkify(doc.intro)}</p>` : ''}
    <p class="updated">${esc(updatedLabel.replace('{date}', doc.updated))}</p>
    ${doc.sections.map((s) => `<section><h2>${esc(s.heading)}</h2>${s.body.map((b) => `<p>${linkify(b)}</p>`).join('')}</section>`).join('\n    ')}`;
}

function page(slug, titles, enBody, deBody) {
  const nav = (lang) => NAV.map(([s, e, d]) => `<a href="/${s}/"${s === slug ? ' aria-current="page"' : ''}>${lang === 'de' ? d : e}</a>`).join('');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(titles[0])} · PARtners</title>
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="icon" href="/favicon-32.png" sizes="32x32">
<link rel="stylesheet" href="/site.css">
</head>
<body class="doc-page">
<!-- Generated by scripts/build-site-legal.mjs from the app's legal texts. Don't edit by hand. -->
<header class="top"><a class="brand" href="/"><img src="/favicon.svg" alt="" width="28" height="28"> PARtners</a>
  <a class="lang" href="?lang=de" data-lang="de" lang="de">Deutsch</a><a class="lang" href="?lang=en" data-lang="en" lang="en" hidden>English</a></header>
<article lang="en" data-lang-block="en">
  <nav>${nav('en')}</nav>${enBody}
</article>
<article lang="de" data-lang-block="de" hidden>
  <nav>${nav('de')}</nav>${deBody}
</article>
<script>
  // German for German phones and browsers, or when chosen with ?lang=de
  var q = new URLSearchParams(location.search).get('lang');
  var de = q ? q === 'de' : /^de\\b/i.test(navigator.language || '');
  if (de) {
    document.documentElement.lang = 'de';
    document.title = ${JSON.stringify(titles[1] + ' · PARtners')};
    document.querySelector('[data-lang-block="en"]').hidden = true;
    document.querySelector('[data-lang-block="de"]').hidden = false;
    document.querySelector('[data-lang="de"]').hidden = true;
    document.querySelector('[data-lang="en"]').hidden = false;
  }
</script>
</body>
</html>
`;
}

function write(slug, html) {
  mkdirSync(join(site, slug), { recursive: true });
  writeFileSync(join(site, slug, 'index.html'), html);
}

const UPDATED_EN = en.legal?.updated ?? 'Last updated {date}';
const UPDATED_DE = de.legal?.updated ?? 'Stand: {date}';

write('privacy', page('privacy', ['Privacy policy', 'Datenschutzerklärung'], docHtml(texts.PRIVACY, UPDATED_EN), docHtml(texts.PRIVACY_DE, UPDATED_DE)));
write('terms', page('terms', ['Terms of service', 'Nutzungsbedingungen'], docHtml(texts.TERMS, UPDATED_EN), docHtml(texts.TERMS_DE, UPDATED_DE)));
write('imprint', page('imprint', ['Imprint', 'Impressum'], docHtml(texts.IMPRINT, UPDATED_EN), docHtml(texts.IMPRINT_DE, UPDATED_DE)));

// Account deletion: Google Play requires a page that works without the app installed.
const mail = (subject) => `<a href="mailto:${texts.CONTACT}?subject=${encodeURIComponent(subject)}">${esc(texts.CONTACT)}</a>`;
const deleteEn = `
    <h1>Delete your PARtners account</h1>
    <p class="intro">You can delete your account and its data at any time, in the app or by email.</p>
    <section><h2>In the app</h2>
      <p>On the <strong>Profile</strong> tab, tap the gear icon to open <strong>Settings</strong>, scroll down and tap <strong>${esc(en.settings.deleteMine)}</strong>, then tap again to confirm. Your account is deleted straight away.</p></section>
    <section><h2>By email</h2>
      <p>If you can't use the app any more, email ${mail('Delete my PARtners account')} from the address you signed up with and ask us to delete your account. We'll do it within 30 days and confirm by email.</p></section>
    <section><h2>What is deleted</h2>
      <p>${esc(en.settings.deleteText)}</p>
      <p>Copies in our backups are overwritten within 7 days. Crash reports aren't linked to your account and are deleted by Firebase Crashlytics after 90 days.</p></section>
    <section><h2>Only some of your data?</h2>
      <p>You can remove your photo, year of birth and gender yourself in <strong>Edit profile</strong>. For anything else, email ${mail('PARtners data request')}.</p></section>`;
const deleteDe = `
    <h1>Dein PARtners-Konto löschen</h1>
    <p class="intro">Du kannst dein Konto und deine Daten jederzeit löschen, in der App oder per E-Mail.</p>
    <section><h2>In der App</h2>
      <p>Tippe im Tab <strong>Profil</strong> auf das Zahnrad, um die <strong>Einstellungen</strong> zu öffnen, scroll nach unten und tippe auf <strong>${esc(de.settings.deleteMine)}</strong>, dann zur Bestätigung noch einmal. Dein Konto wird sofort gelöscht.</p></section>
    <section><h2>Per E-Mail</h2>
      <p>Wenn du die App nicht mehr nutzen kannst, schreib an ${mail('PARtners-Konto löschen')} von der Adresse, mit der du dich registriert hast, und bitte uns, dein Konto zu löschen. Wir erledigen das innerhalb von 30 Tagen und bestätigen es per E-Mail.</p></section>
    <section><h2>Was gelöscht wird</h2>
      <p>${esc(de.settings.deleteText)}</p>
      <p>Kopien in unseren Sicherungen werden innerhalb von 7 Tagen überschrieben. Absturzberichte sind nicht mit deinem Konto verknüpft und werden von Firebase Crashlytics nach 90 Tagen gelöscht.</p></section>
    <section><h2>Nur einen Teil deiner Daten?</h2>
      <p>Dein Foto, Geburtsjahr und Geschlecht kannst du selbst unter <strong>Profil bearbeiten</strong> entfernen. Für alles andere schreib an ${mail('PARtners-Datenanfrage')}.</p></section>`;
write('delete-account', page('delete-account', ['Delete your account', 'Konto löschen'], deleteEn, deleteDe));

console.log('Wrote site/privacy, site/terms, site/imprint and site/delete-account.');
if (String(texts.ADDRESS).startsWith('[')) console.warn('Note: ADDRESS in legal-texts.ts is still a placeholder, so the privacy policy and imprint show it.');
